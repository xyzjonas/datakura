export interface CountryOption {
  code: string
  name: string
  flag: string
}

const LOCALE = 'cs'
let displayNames: Intl.DisplayNames | null = null

const getDisplayNames = () => {
  if (!displayNames) {
    displayNames = new Intl.DisplayNames([LOCALE], { type: 'region' })
  }
  return displayNames
}

/** Localized country name, falls back to the bare code for anything unknown. */
export const countryName = (code: string | null | undefined): string => {
  if (!code) return ''
  try {
    return getDisplayNames().of(code.toUpperCase()) ?? code
  } catch {
    return code
  }
}

/** Flag emoji built from the regional indicator symbols, '' for malformed codes. */
export const countryFlag = (code: string | null | undefined): string => {
  if (!code || !/^[A-Za-z]{2}$/.test(code)) return ''
  return String.fromCodePoint(
    ...code
      .toUpperCase()
      .split('')
      .map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  )
}

let options: CountryOption[] | null = null

/** All countries, sorted by localized name (cached). */
export const countryOptions = (): CountryOption[] => {
  if (!options) {
    options = COUNTRY_CODES.map((code) => ({
      code,
      name: countryName(code),
      flag: countryFlag(code),
    }))
    options.sort((a, b) => a.name.localeCompare(b.name, LOCALE))
  }
  return options
}

/** Case/diacritics-insensitive search over name and code. */
export const filterCountries = (needle: string): CountryOption[] => {
  const normalize = (v: string) =>
    v
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
  const n = normalize(needle.trim())
  if (!n) return countryOptions()
  return countryOptions().filter((o) => normalize(o.name).includes(n) || o.code.toLowerCase() === n)
}
